"""Compare additive Smith invariants in a mixed-characteristic two-colour fibre.

R = (Z/p^e)[u,v]/(u^2-p,v^2-p), X=u and Y=v.
Use the integral polynomial J/(XY) before specialization. Both variables are
nonunits, including at the square-zero directions of R/pR.
Python 3.10+ and NumPy. See proof_audit.md for the predicted 2-by-2 blocks.
"""

import argparse
import hashlib
import json
import platform
from collections import Counter
from itertools import combinations, product as cartesian
from math import gcd, prod
from pathlib import Path

import numpy as np

from check_bezout import beraha_factors, evaluate


def catalogue(n):
    def grow(word, maximum):
        if len(word) == n:
            for a,b,c,d in quadruples:
                if word[a] == word[c] and word[b] == word[d] and word[a] != word[b]:
                    return
            yield tuple(tuple(i for i, val in enumerate(word) if val == j)
                        for j in range(maximum + 1))
            return
        for j in range(maximum + 2):
            yield from grow(word + (j,), max(j, maximum))
    quadruples = list(combinations(range(n), 4))
    return list(grow((0,), 0))


def complement(P, n):
    inv = [None]*n
    for block in P:
        for i, b in enumerate(block):
            inv[b] = block[i-1]
    seen = set()
    K = []
    for j in range(n):
        if j in seen:
            continue
        cycle = []
        while j not in seen:
            seen.add(j)
            cycle.append(j)
            j = inv[(j+1) % n]
        K.append(tuple(sorted(cycle)))
    return tuple(K)


def joins(P, Q):
    # Compute the equivalence classes generated by both partitions.
    sets = [set(b) for b in P]
    for block in Q:
        attached = [s for s in sets if not s.isdisjoint(block)]
        others = [s for s in sets if s.isdisjoint(block)]
        sets = others + [set.union(*attached)]
    return len(sets)


def exponents(n):
    part = catalogue(n)
    kreweras = [complement(P,n) for P in part]
    if set(part) != set(kreweras):
        raise ArithmeticError("the complement is not a permutation")
    C = len(part)
    a = np.empty((C,C), dtype=np.int16)
    b = np.empty_like(a)
    for i,P in enumerate(part):
        for j in range(i+1):
            counts = joins(P,part[j]), joins(kreweras[i],kreweras[j])
            if counts[0] - counts[1] != len(P) + len(part[j]) - n - 1:
                raise ArithmeticError("Euler relation failed")
            a[i,j] = a[j,i] = counts[0] - 1
            b[i,j] = b[j,i] = counts[1] - 1
    return a,b


def regular_matrix(a,b,p,e):
    # The basis in each of four row/column blocks is 1,u,v,uv.
    C = len(a)
    matrix = np.zeros((4*C,4*C), dtype=np.int32)
    m = p**e
    for col in range(4):
        i, j = a + (col & 1), b + (col >> 1)
        basis = (i%2) + 2*(j%2)
        exponent = i//2 + j//2
        for row in range(4):
            block = matrix[row*C:(row+1)*C,col*C:(col+1)*C]
            for k in range(e):
                block[(basis == row) & (exponent == k)] = pow(p,k,m)
    return matrix


def additive_profile(matrix,p,e):
    # Reduce by unit pivots. When all remaining entries are multiples of p,
    # divide the remaining block by p and continue over the smaller modulus.
    counts = []
    A = matrix
    for j in range(e):
        m = p**(e-j)
        i, last = 0, len(A)
        while i < last:
            units = np.flatnonzero(A[i:,i] % p)
            if not len(units):
                last -= 1
                if i != last:
                    A[:,[i,last]] = A[:,[last,i]]
                continue
            row = i + units[0]
            if i != row:
                A[[row,i],:] = A[[i,row],:]
            coeff = (A[i+1:,i] * pow(int(A[i,i]),-1,m)) % m
            to_update = np.flatnonzero(coeff)
            if len(to_update):
                global_rows = i+1+to_update
                A[global_rows,i+1:] = (A[global_rows,i+1:] -
                        coeff[to_update,None]*A[i,i+1:]) % m
            i += 1
        counts.append(i)
        remainder = A[i:,i:]
        if np.any(remainder%p):
            raise ArithmeticError("nondivisible residual block")
        A = remainder//p
    return counts + [len(A)]


def height_counts(n):
    # Independent transfer over Dyck paths, without using the partition list.
    counts = {(0,0):1}
    for _ in range(2*n):
        nxt = Counter()
        for (pos,highest),v in counts.items():
            nxt[pos+1,max(highest,pos+1)] += v
            if pos:
                nxt[pos-1,highest] += v
        counts = nxt
    return {h:v for (i,h),v in counts.items() if i == 0}


def predicted(n,p,e):
    factors = beraha_factors(n+1)
    counts = Counter()
    def valuation(x):
        j = 0
        while j < e and x % p == 0:
            x //= p
            j += 1
        return j
    for h,multiplicity in height_counts(n).items():
        values = [prod(evaluate(factors[d], z) for d in range(3,h+2)) for z in (p,-p)]
        A = (values[0]+values[1])//2
        B = (values[0]-values[1])//(2*p)
        if A+p*B != values[0] or A-p*B != values[1]:
            raise ArithmeticError("failed evaluation of A+Buv")
        det = abs(values[0]*values[1])
        for g in [gcd(A,B), gcd(A,p*B)]:
            for elem in [g, det//g if g else 0]:
                counts[valuation(elem)] += multiplicity
    return [counts[j] for j in range(e+1)]


def test_small_reducer():
    # Exhaustively enumerate a few tiny maps, including pivots off the diagonal
    # and zero divisors. Every reduction modulo p^j has image cardinality
    # p^sum_i max(j-v_i,0), so the three checks also distinguish the bins.
    for p,e in [(2,3),(3,3)]:
        for coeffs in [[0,0,0,0],[p,0,0,p*p],[0,1,p*p,p],
                       [1,p,p,p*p],[p,p*p,p,p*(p+1)]]:
            raw = np.array(coeffs,dtype=np.int32).reshape(2,2)
            counts = additive_profile(raw.copy() % (p**e),p,e)
            for j in range(1,e+1):
                m = p**j
                a,b,c,d = coeffs
                observed = {((a*i+b*t)%m, (c*i+d*t)%m)
                            for i,t in cartesian(range(m), repeat=2)}
                if len(observed) != p**sum(h*max(j-v,0) for v,h in enumerate(counts)):
                    raise ArithmeticError("tiny exhaustive control failed")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--orders",default="6,7")
    ap.add_argument("--write",type=Path)
    args = ap.parse_args()
    test_small_reducer()
    tests = []
    for n in map(int,args.orders.split(",")):
        if not 1 <= n <= 8:
            ap.error("orders must be between 1 and 8")
        a,b = exponents(n)
        for p,e in [(2,3),(3,3)]:
            A = regular_matrix(a,b,p,e)
            if A.shape != (4*sum(height_counts(n).values()),)*2:
                raise ArithmeticError("dimension check failed")
            digest = hashlib.sha256(A.astype("<u4",copy=False).tobytes(order="C")).hexdigest()
            seen = additive_profile(A,p,e)
            expected = predicted(n,p,e)
            if seen != expected:
                raise AssertionError((n,p,e,seen,expected))
            tests.append(dict(n=n,partitions=len(a),scalar_dimension=len(A),p=p,e=e,
                              additive_valuation_counts=seen, matrix_sha256_u32le=digest))
            print(f"n={n}, p={p}, e={e}, additive multiplicities {seen}",flush=True)
    if args.write:
        record = {"ring":"(Z/p^e)[u,v]/(u^2-p,v^2-p)",
                  "matrix":"J/(XY) formed over Z[X,Y] before X=u,Y=v",
                  "last_bin":"valuation at least e",
                  "python":platform.python_version(),"numpy":np.__version__,"checks":tests}
        args.write.write_text(json.dumps(record,indent=2)+"\n",encoding="utf-8")


if __name__ == "__main__":
    main()
