"""Check a supplied polynomial equivalence independently. Requires Python 3 and SymPy."""
import argparse
import ast
import json
from math import comb
from pathlib import Path
from sympy import Matrix, Poly, ZZ, diag, symbols


def expression(source, names):
    if not isinstance(source,str):
        raise ValueError("expected a polynomial string")
    def convert(node):
        if isinstance(node,ast.Name) and node.id in names:
            return names[node.id]
        if isinstance(node,ast.Constant) and type(node.value) is int:
            return node.value
        if isinstance(node,ast.UnaryOp) and isinstance(node.op,ast.USub):
            return -convert(node.operand)
        if isinstance(node,ast.BinOp):
            a,b=convert(node.left),convert(node.right)
            if isinstance(node.op,ast.Add): return a+b
            if isinstance(node.op,ast.Sub): return a-b
            if isinstance(node.op,ast.Mult): return a*b
            if isinstance(node.op,ast.Pow) and type(b) is int and 0<=b<=128: return a**b
        raise ValueError("unexpected polynomial syntax")
    return convert(ast.parse(source, mode='eval').body)


def components(generators):
    """Equivalence classes generated by one or more permutations."""
    sets=list(range(len(generators[0])))
    def root(i):
        while i!=sets[i]:
            sets[i]=sets[sets[i]]
            i=sets[i]
        return i
    for g in generators:
        for i,j in enumerate(g):
            sets[root(i)]=root(j)
    return len({root(i) for i in range(len(sets))})


def check(file):
    with file.open(encoding='utf-8-sig') as stream: data=json.load(stream)
    n=data['n']
    rows=[tuple(p) for p in data['order']]
    size=comb(2*n,n)//(n+1)
    assert len(set(rows))==len(rows)==size
    heights=[]
    for p in rows:
        assert len(p)==2*n and sorted(p)==list(range(2*n))
        stack=[]
        height=0
        for i,j in enumerate(p):
            assert p[j]==i and i!=j
            if j>i:
                stack.append(j)
                height=max(height,len(stack))
            else:
                assert stack.pop()==i
        assert not stack
        heights.append(height)
    x,X,Y=symbols('x X Y')
    two=data['ring']=='Z[X,Y]'
    assert two or data['ring']=='Z[x]'
    variables=(X,Y) if two else (x,)
    names={str(s):s for s in variables}
    f0=Poly(0,x,domain=ZZ)
    f1=common=Poly(1,x,domain=ZZ)
    target=[]
    for _ in range(n):
        f0,f1=f1,Poly(x,x)*f1-f0
        common=common.lcm(f1).monic()
        if two:
            coeff=Poly(common.as_expr()*x,x).terms()
            assert all(degree%2==0 for (degree,),_ in coeff)
            target.append(sum(c*(X*Y)**(degree//2) for (degree,),c in coeff))
        else:
            target.append(common.as_expr())
    D=diag(*[target[h-1] for h in heights])
    assert all((D[i,i]-expression(f,names)).expand()==0 for i,f in enumerate(data['diagonal']))
    assert len(data['diagonal'])==size
    if two:
        pi=[tuple(p[2*j+1]//2 for j in range(n)) for p in rows]
        dual=[tuple(a.index((j+1)%n) for j in range(n)) for a in pi]
        G=Matrix(size,size,lambda i,j: X**components((pi[i],pi[j]))*Y**components((dual[i],dual[j])))
    else:
        G=Matrix(size,size,lambda i,j: x**components((rows[i],rows[j])))
    def unpack(items):
        matrix=Matrix.zeros(size)
        used=set()
        for i,j,f in items:
            assert 0<=i<size and 0<=j<size and (i,j) not in used
            used.add((i,j))
            matrix[i,j]=expression(f,names)
        return matrix
    L,V=unpack(data['left']),unpack(data['quotient'])
    assert all(Poly(a,*variables,domain=ZZ).is_zero for a in L*G-D*V)
    assert L.det(method='domain-ge')==V.det(method='domain-ge')==1
    return dict(certificate=file.name,order=n,dimension=size,ring=data['ring'],verified=True)


if __name__=='__main__':
    if not __debug__: raise RuntimeError("Run the verifier with Python assertions enabled.")
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('certificates',type=Path,nargs='+')
    args=ap.parse_args()
    for file in args.certificates: print(json.dumps(check(file)))
